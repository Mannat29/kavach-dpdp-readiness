def get_simulation(sim_id: int, conn=None) -> Optional[Dict]:
    """Retrieve an existing simulation by ID."""
    if conn is None:
        conn = get_db()

    cur = conn.cursor()
    cur.execute(
        """SELECT id, scenario, aware_at, device_protected, severity, counts_json, drafts_json, created_at
           FROM breach_simulations WHERE id = ?""",
        (sim_id,),
    )
    row = cur.fetchone()
    if not row:
        return None

    counts = json.loads(row["counts_json"]) if row["counts_json"] else {}
    drafts = json.loads(row["drafts_json"]) if row["drafts_json"] else {}

    scenario_def = get_scenario_by_id(row["scenario"])
    scenario_title = scenario_def.get("title", row["scenario"]) if scenario_def else row["scenario"]
    checklist = scenario_def.get("first_hour_checklist", []) if scenario_def else []
    exposure_types = scenario_def.get("exposure_types", ["confidentiality"]) if scenario_def else ["confidentiality"]

    # Recompute clocks relative to aware_at
    aware_at_str = row["aware_at"]
    try:
        aware_at_dt = datetime.datetime.fromisoformat(aware_at_str.replace("Z", "+00:00"))
    except Exception:
        aware_at_dt = datetime.datetime.now(datetime.timezone.utc)

    now_dt = datetime.datetime.now(datetime.timezone.utc)
    elapsed_seconds = max(0, int((now_dt - aware_at_dt).total_seconds()))
    deadline_dt = aware_at_dt + datetime.timedelta(hours=BREACH_STAGE_2_HOURS)
    seconds_remaining = int((deadline_dt - now_dt).total_seconds())

    clocks = {
        "aware_at": aware_at_dt.isoformat(),
        "stage_1": {
            "title": "Stage 1: Initial Intimation to Board",
            "requirement": BREACH_STAGE_1_DESCRIPTION,
            "elapsed_seconds": elapsed_seconds,
            "elapsed_display": _format_time_elapsed(elapsed_seconds),
            "note": "No fixed statutory deadline; fiduciary must inform the Board without delay.",
        },
        "stage_2": {
            "title": "Stage 2: Detailed Incident Report to Board",
            "requirement": BREACH_STAGE_2_DESCRIPTION,
            "deadline": deadline_dt.isoformat(),
            "deadline_timestamp": deadline_dt.timestamp(),
            "seconds_remaining": seconds_remaining,
            "hours_limit": BREACH_STAGE_2_HOURS,
            "note": "Extendable on written request to the Board.",
        },
        "individual_notice": {
            "requirement": BREACH_INDIVIDUAL_NOTICE_NOTE,
            "note": "Affected people must be told without delay; check in the Rules text whether this applies in every case (verify)",
        },
    }

    recipients = counts.get("recipients", [])

    return {
        "id": row["id"],
        "scenario": row["scenario"],
        "scenario_title": scenario_title,
        "exposure_types": exposure_types,
        "aware_at": row["aware_at"],
        "device_protected": row["device_protected"],
        "severity": row["severity"],
        "counts": counts,
        "drafts": drafts,
        "clocks": clocks,
        "first_hour_checklist": checklist,
        "recipients": recipients,
        "recipients_disclaimer": "The tool cannot send anything. Notices must be sent manually.",
        "created_at": row["created_at"],
    }
