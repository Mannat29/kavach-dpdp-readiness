HIGH_IMPACT_CATEGORIES = {"aadhaar", "pan", "bank_account", "health_term"}
SEVERITY_NOTE = "Severity is Kavach's own estimate to help prioritise, not a legal threshold."


def load_scenarios() -> List[Dict]:
    """Load breach scenarios from breach_scenarios.yaml."""
    rules_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "rules")
    yaml_path = os.path.join(rules_dir, "breach_scenarios.yaml")
    if not os.path.exists(yaml_path):
        return []
    with open(yaml_path, "r", encoding="utf-8") as f:
        data = yaml.safe_load(f)
    return data or []


def get_scenario_by_id(scenario_id: str) -> Optional[Dict]:
    """Retrieve a single breach scenario definition by id."""
    scenarios = load_scenarios()
    for s in scenarios:
        if s.get("id") == scenario_id:
            return s
    return None


def _format_time_elapsed(seconds: int) -> str:
    """Format elapsed seconds into human-readable string."""
    hours = seconds // 3600
    minutes = (seconds % 3600) // 60
    secs = seconds % 60
    if hours > 0:
        return f"{hours}h {minutes}m elapsed"
    if minutes > 0:
        return f"{minutes}m {secs}s elapsed"
    return f"{secs}s elapsed"


def _build_board_intimation_draft(
    scenario_title: str,
    scenario_desc: str,
    exposure_types: List[str],
    affected_sources: List[str],
    records_count: int,
    confirmed_people: int,
    possible_people: int,
    people_range: str,
    categories: Dict[str, Dict],
    aware_at_dt: datetime.datetime,
) -> str:
    """Generate Draft (a): Preliminary Section 8(6) intimation to the Board."""
    exposure_str = ", ".join(t.capitalize() for t in exposure_types)
    sources_str = ", ".join(affected_sources)

    cat_names = [c for c in categories.keys() if c != "minors"]
    categories_str = ", ".join(c.replace("_", " ").title() for c in cat_names) or "None detected"

    hi_cats = [c.replace("_", " ").title() for c, data in categories.items() if data.get("is_high_impact")]
    hi_str = ", ".join(hi_cats) if hi_cats else "None"

    consequences = []
    if "aadhaar" in categories or "pan" in categories or "bank_account" in categories:
        consequences.append("Potential financial phishing, impersonation, or unauthorized credential misuse.")
    if "health_term" in categories:
        consequences.append("Unauthorized exposure of confidential health/treatment records.")
    if "availability" in exposure_types:
        consequences.append("Temporary unavailability of business or patient service data.")
    if not consequences:
        consequences.append("Potential unsolicited communications or privacy intrusion.")
    consequences_str = " ".join(consequences)

    return f"""# DRAFT, SIMULATION, review before sending

## DPDP Section 8(6) Breach Intimation to the Data Protection Board of India

**Notice Type:** Preliminary Breach Intimation
**Generated At:** {aware_at_dt.strftime("%Y-%m-%d %H:%M:%S UTC")}

### 1. Data Fiduciary Information
- **Business Name:** [BUSINESS_NAME]
- **Contact Person:** [CONTACT_PERSON]
- **Contact Details:** [PHONE_OR_EMAIL]
- **Date & Time of Notice:** [DATE_TIME]

### 2. Nature of the Incident
- **Incident Summary:** {scenario_title} - {scenario_desc}
- **Exposure Type(s):** {exposure_str}
- **Affected Sources / Systems:** {sources_str}

### 3. Extent of Exposure
- **Total Compromised Records:** {records_count}
- **Affected Individuals (Estimated Range):** {people_range} ({confirmed_people} confirmed, {possible_people} possible matches)
- **Data Categories Involved:** {categories_str}
- **High-Impact Categories Flagged:** {hi_str}

### 4. Timing
- **Awareness Timestamp:** {aware_at_dt.isoformat()}
- **Reporting Deadline:** Stage 1 intimation submitted without delay.

### 5. Location
- **Storage Location:** {sources_str}

### 6. Likely Consequences
- {consequences_str}

---
*Note: This is a draft generated by the Kavach Breach Simulator for review by the Data Protection Officer or business owner before dispatch to the Board.*
"""


