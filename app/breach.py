"""Breach blast-radius simulation module for Kavach.

Provides blast-radius calculation, risk severity scoring, statutory DPDP notification
clocks, draft generation, and hash-chained ledger audit logging.
Everything produced is a SIMULATION and DRAFT; never mix simulated incidents with real ones.
"""

